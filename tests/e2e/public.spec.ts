import { test, expect, noPageOverflow } from './fixtures'

test('Home search opens all results; report list restores the viewed page', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '검색 열기', exact: true }).click()
  const search = page.getByRole('combobox').first()
  await search.fill('리포트 1')
  await expect(page.getByRole('listbox', { name: '검색결과 미리보기' })).toBeVisible()
  await page.getByRole('link', { name: '전체 검색결과 보기' }).click()
  await expect(page).toHaveURL(/\/search\?q=/)
  await expect(page.getByText('[검증용] 리포트 1', { exact: true }).first()).toBeVisible()
  await page.goto('/research?page=2')
  const first = page.getByRole('list', { name: '리포트 목록' }).getByRole('link').first()
  const href = await first.getAttribute('href')
  await first.click()
  await expect(page).toHaveURL(new RegExp(href!.split('?')[0]))
  await page.getByRole('link', { name: /목록으로/ }).click()
  await expect(page).toHaveURL(/research\?page=2/)
  await expect(page.getByRole('list', { name: '리포트 목록' })).toBeVisible()
  await noPageOverflow(page)
})

test('Prepared PDF opens, changes page and zoom, and exposes the original download', async ({ page, isMobile }) => {
  const packs: string[] = []
  page.on('request', request => { if (new URL(request.url()).searchParams.has('pages')) packs.push(request.url()) })
  await page.goto('/research/a0000000000000000000000000000001')
  const reader = page.locator('[data-pdf-reader-mode="prepared"]')
  await expect(reader).toBeVisible()
  await expect(reader.locator('img').first()).toBeVisible()
  await page.getByRole('button', { name: '다음 페이지', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: 'PDF 페이지' })).toHaveValue('2')
  await page.getByRole('combobox', { name: 'PDF 확대' }).selectOption('0.75')
  await page.getByRole('spinbutton', { name: 'PDF 페이지' }).fill('3')
  await page.getByRole('spinbutton', { name: 'PDF 페이지' }).press('Enter')
  await expect(page.getByRole('button', { name: '다음 페이지', exact: true })).toBeDisabled()
  await expect(reader.locator('img').first()).toBeVisible()
  expect(packs.length, 'The page pack is fetched once, not on every page turn').toBe(1)
  if (!isMobile) {
    await page.getByRole('button', { name: '전체 화면', exact: true }).click()
    await page.getByRole('button', { name: '두 페이지', exact: true }).click()
    await page.getByRole('button', { name: '이전 페이지', exact: true }).click()
    await expect(reader.locator('[data-pdf-visible-pages]')).toHaveAttribute('data-pdf-visible-pages', '1,2')
    await page.getByRole('button', { name: '전체 화면 닫기' }).click()
  }
  const download = page.getByRole('link', { name: /PDF 다운로드/ }).first()
  const response = await page.request.get((await download.getAttribute('href'))!)
  expect(response.status()).toBe(200)
  expect((await response.body()).subarray(0, 5).toString()).toBe('%PDF-')
  await noPageOverflow(page)
})
