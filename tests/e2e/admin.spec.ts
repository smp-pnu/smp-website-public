import { test, expect, registerTestAdmin, adminApi, connectTestDrive, noPageOverflow, adminOrigin } from './fixtures'
import { samplePdf } from '../../admin-lab/sample'

test.use({ baseURL: adminOrigin, ignoreHTTPSErrors: true })
test.beforeEach(async ({ page, context }) => { await registerTestAdmin(page, context) })

test('Passkey logout/login preserves a secure 24-hour session', async ({ page, context }) => {
  const session = (await context.cookies()).find(c => c.name === '__Host-smp_admin')!
  expect(session.httpOnly && session.secure && session.sameSite === 'Strict').toBe(true)
  expect(session.expires - Date.now() / 1000).toBeGreaterThan(23 * 3600)
  if (await page.getByRole('button', { name: '관리 메뉴 열기' }).isVisible()) await page.getByRole('button', { name: '관리 메뉴 열기' }).click()
  await page.getByRole('button', { name: '로그아웃', exact: true }).click()
  expect((await context.request.get('/api/cms/research')).status()).toBe(401)
  await page.getByRole('button', { name: '패스키로 로그인', exact: true }).click()
  await expect(page.getByRole('heading', { name: '운영 현황', exact: true })).toBeVisible()
  await noPageOverflow(page)
})

test('Report PDF upload, review, editing and publish queue persist after reload', async ({ page }) => {
  await connectTestDrive(page)
  await page.goto('/#upload')
  await page.getByLabel('AI로 입력 후보 보완').uncheck()
  await expect(page.getByLabel('등록할 PDF 선택')).toBeEnabled()
  const pdf = samplePdf(0)
  await page.getByLabel('등록할 PDF 선택').setInputFiles({ name: 'QA-synthetic-report.pdf', mimeType: 'application/pdf', buffer: Buffer.from(await pdf.arrayBuffer()) })
  await expect(page.getByRole('heading', { name: '입력 내용 검토' })).toBeVisible()
  // A missing semester must be reviewed instead of silently published.
  await expect(page.getByLabel('PDF 원문과 입력 내용을 확인했어요.')).toBeDisabled()
  await page.getByLabel('학기', { exact: true }).fill('2026-2')
  await page.getByRole('button', { name: '초안 저장', exact: true }).click()
  await expect(page.getByLabel('PDF 원문과 입력 내용을 확인했어요.')).toBeEnabled()
  await page.getByLabel('PDF 원문과 입력 내용을 확인했어요.').check()
  await page.getByRole('button', { name: '검토 완료 · 게시 초안 만들기' }).click()
  await expect(page.getByRole('heading', { name: '리포트 편집' })).toBeVisible()
  await page.getByLabel('제목', { exact: true }).fill('QA 리포트 수정 저장 확인')
  await page.getByRole('button', { name: '초안 저장', exact: true }).click()
  await expect(page.getByRole('button', { name: '초안 저장', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '게시', exact: true })).toBeEnabled()
  await page.reload()
  await expect(page.getByLabel('제목', { exact: true })).toHaveValue('QA 리포트 수정 저장 확인')
  await page.getByRole('button', { name: '게시', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: '확인', exact: true }).click()
  // The loading label is a nested live status rather than a button name.
  await expect(page.getByRole('button').filter({ has: page.getByRole('status').filter({ hasText: '게시 준비 중' }) })).toBeDisabled()
  const entries = await adminApi(page, '/cms/research')
  expect(entries.items).toHaveLength(1)
  expect(entries.items[0].pending).toBe(true)
  const files = await (await page.request.get('/__qa/files', { headers: { 'X-SMP-QA': 'local-only' } })).json()
  const originals = files.filter((f: { bytes: number }) => f.bytes > 0)
  expect(originals).toHaveLength(1)
  expect(originals[0].bytes).toBe(pdf.size)
  expect(originals[0].permissions).toEqual([{ type: 'user', role: 'owner' }])
  await noPageOverflow(page)
})

test('Notice composition, preview and publication retain saved body', async ({ page }) => {
  await page.goto('/#notice')
  await page.getByRole('button', { name: '공지 작성', exact: true }).click()
  await page.getByLabel('공지 제목', { exact: true }).fill('QA 가상 공지')
  await page.getByRole('textbox', { name: '공지 본문' }).fill('자동 점검용 공지 본문입니다. 실제 학회 게시글이 아닙니다.')
  await page.getByRole('button', { name: '미리보기', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'QA 가상 공지' })).toBeVisible()
  await page.getByRole('button', { name: '초안 저장', exact: true }).click()
  await expect(page.getByRole('button', { name: '초안 저장', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '게시', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '게시', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: '확인', exact: true }).click()
  await expect(page.getByRole('button', { name: '변경사항 게시', exact: true })).toBeDisabled()
  await page.reload()
  await expect(page.getByLabel('공지 제목', { exact: true })).toHaveValue('QA 가상 공지')
  await expect(page.getByRole('textbox', { name: '공지 본문' })).toContainText('자동 점검용 공지 본문')
  const list = await adminApi(page, '/cms/notice')
  expect(list.items).toHaveLength(1)
  expect(list.items[0].approvedRevision).toBe(list.items[0].revision)
  await noPageOverflow(page)
})

